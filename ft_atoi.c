#include "libft.h"

int	ft_atoi(char *s)
{
	int	i;
	int	j;
	int	r;

	i = 0;
	j = 0;
	r = 1;
	while ((s[i] >= 9 && s[i] <= 13) || s[i] == ' ')
	{
		i++;
	}
	if (s[i] == '-' || s[i] == '+')
	{
		if (s[i] == '-')
			r = -1;
		i++;
	}
	while (s[i] != '\0' && (s[i] <= 57 && s[i] >= 48))
	{
		j = j * 10;
		j += s[i] - 48;
		i++;
	}
	return (j * r);
}
